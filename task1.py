print("Программа для вычисления общего сопротивления цепи")

r1 = float(input("Введите сопротивление R1 (Ом): "))
r2 = float(input("Введите сопротивление R2 (Ом): "))
print("Тип соединения:")
print("  1 - последовательное")
print("  2 - параллельное")
choice = input("Введите 1 или 2: ")

if choice == "1":
    r_total = r1 + r2
    print("Сопротивление последовательного соединения:", r_total, "Ом")
elif choice == "2":
    if r1 + r2 == 0:
        print("Оба сопротивления равны нулю, сопротивление цепи не определено.")
    else:
        r_total = (r1 * r2) / (r1 + r2)
        print("Сопротивление параллельного соединения:", r_total, "Ом")
else:
    print("Неверный тип соединения. Введите 1 или 2.")